// The module table the boot code needs, shared by the two halves of the release split.
//
// The player's exe links the libraries lifted from their own dump, so IT owns this table. xc2_rt.dll holds the
// runtime and the boot code and must not reference any lifted symbol, so the exe hands the table over before the
// boot code runs (upstream: fefw_rt.dll / fefw_stub.cpp do the same, their boot code never names a lifted module).
#pragma once
#include <cstdint>

#include <nxrecomp/ctx.h>   // NxModule

struct ModEntry {
    const char *file;      // the ExeFS file name: rtld, main, subsdk0..3, sdk
    const NxModule *nx;    // base address and entry, generated by the lifter
    const uint32_t *abi;   // the ABI version the module was lifted against
};

// Called by the exe before xc2_rt_main. The table has to outlive the call (a static array in the exe is fine).
// The DLL exports it (see xc2_rt.def); the exe imports it from there.
extern "C" void xc2_rt_set_modules(const ModEntry *mods, int count);
